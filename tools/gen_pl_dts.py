#!/usr/bin/env python3
"""Generate Linux device-tree fragments for the PZ-ZU2CG Linux reference design.

Usage:  python3 tools/gen_pl_dts.py [design.xsa [design.xdc]]
Defaults to projects/pz_zu2cg_linux/pz_zu2cg_linux.{xsa,xdc}. Writes:

  dts/pz_zu2cg_pl.dtsi     PL hardware nodes (AXI GPIO/IIC, gmii_to_rgmii) read from the
                           XSA's system.hwh: addresses, widths, defaults, interrupts. Node
                           labels match the AMD device-tree generator (instance names), so
                           PetaLinux users don't need this file: its pl.dtsi is equivalent.
  dts/pz_zu2cg_board.dtsi  What the XSA can't know: LEDs, keys, EEPROM, RTL8211F PHY (reset,
                           RGMII delays) and connector-pin names for the header GPIOs. Use it
                           as PetaLinux's system-user.dtsi, or include it after the PL file.
"""
import re
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
xsa = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "projects/pz_zu2cg_linux/pz_zu2cg_linux.xsa"
xdc = Path(sys.argv[2]) if len(sys.argv) > 2 else xsa.with_suffix(".xdc")
out = ROOT / "dts"

PL_PS_IRQ0_SPI = 89      # pl_ps_irq0[0] is GIC SPI 89 (IRQ 121) on Zynq UltraScale+
PS_GPIO_EMIO0 = 78       # PS GPIO line of EMIO bit 0 (after the 78 MIO lines)
PHY_ADDR = 2             # RTL8211F strap address
LED_NAMES = {"gpio_led": [f"led{i}" for i in range(1, 6)],
             "gpio_led_core": [f"core-led{i}" for i in range(1, 4)]}
LED_TRIGGER = {("gpio_led_core", 0): "heartbeat"}
HEADERS = {"jm1": "gpio_jm1", "j19": "gpio_j19", "j20": "gpio_j20"}

# --- Read the hardware handoff -------------------------------------------------------
with zipfile.ZipFile(xsa) as z:
    hwh = ET.fromstring(z.read("system.hwh"))

cells = {}
for m in hwh.iter("MODULE"):
    params = {p.get("NAME"): p.get("VALUE") for p in m.iter("PARAMETER")}
    ports = {p.get("NAME"): [f"{c.get('INSTANCE')}/{c.get('PORT')}" for c in p.iter("CONNECTION")]
             for p in m.iter("PORT")}
    cells[m.get("INSTANCE")] = (m.get("MODTYPE"), params, ports)

ps = next(n for n, (t, _, _) in cells.items() if t == "zynq_ultra_ps_e")
addr = {}
for m in hwh.iter("MODULE"):
    if m.get("INSTANCE") == ps:
        for r in m.iter("MEMRANGE"):
            addr[r.get("INSTANCE")] = (int(r.get("BASEVALUE"), 16), int(r.get("HIGHVALUE"), 16))

# pl_ps_irq0 bit of each interrupt source, through the xlconcat feeding it
irq = {}
src = cells[ps][2]["pl_ps_irq0"][0].split("/")[0]
_, cp, cports = cells[src]
bit = 0
for i in range(int(cp["NUM_PORTS"])):
    for s in cports.get(f"In{i}", []):
        irq[s.split("/")[0]] = PL_PS_IRQ0_SPI + bit
    bit += int(cp[f"IN{i}_WIDTH"])

pl_clk = {c.split("/")[0]: n for n in ("pl_clk0", "pl_clk1", "pl_clk2", "pl_clk3")
          for c in cells[ps][2].get(n, [])}

# Connector pin of every header GPIO bit, from the project XDC comments
line_names = {h: {} for h in HEADERS}
for l in xdc.read_text().splitlines():
    m = re.search(r"get_ports \{(\w+?)(_hi)?_tri_io\[(\d+)\]\}\]\s*;#\s*(\S+)", l)
    if m and m.group(1) in line_names:
        line_names[m.group(1)][int(m.group(3)) + (32 if m.group(2) else 0)] = m.group(4)


def reg(base, high):
    size = high - base + 1
    return f"<0x{base >> 32:x} 0x{base & 0xffffffff:x} 0x{size >> 32:x} 0x{size & 0xffffffff:x}>"


def common(name, params):
    clk = {"pl_clk0": "PL0_REF", "pl_clk1": "PL1_REF"}[pl_clk[name]]
    s = [f"reg = {reg(*addr[name])};", f"clocks = <&zynqmp_clk {clk}>;"]
    if name in irq:
        s += ["interrupt-parent = <&gic>;", f"interrupts = <GIC_SPI {irq[name]} IRQ_TYPE_LEVEL_HIGH>;"]
    return s


def node(label, unit, body, indent="\t\t"):
    lines = [f"{indent}{label}: {unit} {{"] + [f"{indent}\t{b}" for b in body] + [f"{indent}}};"]
    return "\n".join(lines)


hdr = f"""// SPDX-License-Identifier: GPL-2.0
/*
 * {{what}}
 * Generated by tools/gen_pl_dts.py from {xsa.relative_to(ROOT) if xsa.is_relative_to(ROOT) else xsa}
 * - do not edit; change the generator or the Vivado design and regenerate.
 */
"""

# --- PL hardware nodes ---------------------------------------------------------------
pl = []
for name in sorted(addr, key=lambda n: addr[n][0]):
    t, p, _ = cells[name]
    if t == "axi_gpio":
        dual = p["C_IS_DUAL"] == "1"
        b = ['compatible = "xlnx,axi-gpio-2.0", "xlnx,xps-gpio-1.00.a";'] + common(name, p) + [
            "gpio-controller;", "#gpio-cells = <2>;"]
        if p["C_INTERRUPT_PRESENT"] == "1":
            b += ["interrupt-controller;", "#interrupt-cells = <2>;", "#address-cells = <0>;"]
        for ch in ([""] + (["-2"] if dual else [])):
            k = "_2" if ch else ""
            b += [f"xlnx,gpio{'2' if ch else ''}-width = <{p['C_GPIO2_WIDTH' if ch else 'C_GPIO_WIDTH']}>;",
                  f"xlnx,all-inputs{ch} = <{p['C_ALL_INPUTS' + k]}>;",
                  f"xlnx,all-outputs{ch} = <{p['C_ALL_OUTPUTS' + k]}>;",
                  f"xlnx,dout-default{ch} = <{p['C_DOUT_DEFAULT' + k]}>;",
                  f"xlnx,tri-default{ch} = <{p['C_TRI_DEFAULT' + k]}>;"]
        b += [f"xlnx,interrupt-present = <{p['C_INTERRUPT_PRESENT']}>;", f"xlnx,is-dual = <{p['C_IS_DUAL']}>;"]
        pl.append(node(name, f"gpio@{addr[name][0]:x}", b))
    elif t == "axi_iic":
        b = ['compatible = "xlnx,axi-iic-2.1", "xlnx,xps-iic-2.00.a";'] + common(name, p) + [
            "#address-cells = <1>;", "#size-cells = <0>;",
            f"clock-frequency = <{p['C_IIC_FREQ']}>;",
            f"xlnx,s-axi-aclk-freq-hz = <{p['C_S_AXI_ACLK_FREQ_HZ']}>;"]
        pl.append(node(name, f"i2c@{addr[name][0]:x}", b))

conv = [n for n, (t, _, _) in cells.items() if t == "gmii_to_rgmii"]
ddr = [n for n, (t, _, _) in cells.items() if t == "ddr4"]

s = [hdr.format(what="PZ-ZU2CG Linux reference design: PL peripherals"),
     "#include <dt-bindings/clock/xlnx-zynqmp-clk.h>",
     "#include <dt-bindings/interrupt-controller/arm-gic.h>",
     "#include <dt-bindings/interrupt-controller/irq.h>", "",
     "/ {",
     "\tamba_pl: amba_pl {",
     '\t\tcompatible = "simple-bus";',
     "\t\t#address-cells = <2>;",
     "\t\t#size-cells = <2>;",
     "\t\tranges;", "",
     "\n\n".join(pl),
     "\t};"]
for name in ddr:
    base, high = addr[name]
    s += ["",
          f"\t/*",
          f"\t * PL DDR4 ({name}, {cells[name][1]['C0.DDR4_MemoryPart']}) behind M_AXI_HPM0_FPD,",
          f"\t * {(high - base + 1) >> 20} MB at 0x{base:x}, kept out of Linux's RAM for DMA buffers.",
          f"\t * pl_ddr4_dma is a coherent DMA pool: a DMA-capable node (e.g. an AXI DMA added to",
          f"\t * the PL) takes it with memory-region = <&pl_ddr4_dma>, and dma_alloc_coherent() for",
          f"\t * that device then allocates here (mapped uncached). PL logic can also use the MIG",
          f"\t * directly; /dev/mem reaches it too. Build with -DPL_DDR4_AS_RAM to make it system",
          f"\t * RAM instead. Either way the bitstream must be loaded before Linux starts (U-Boot",
          f"\t * does it from its preboot command).",
          f"\t */",
          "#ifdef PL_DDR4_AS_RAM",
          f"\tmemory@{base:x} {{",
          '\t\tdevice_type = "memory";',
          f"\t\treg = {reg(base, high)};",
          "\t};",
          "#else",
          "\treserved-memory {",
          "\t\t#address-cells = <2>;",
          "\t\t#size-cells = <2>;",
          "\t\tranges;", "",
          f"\t\tpl_ddr4_dma: pl-ddr4-dma@{base:x} {{",
          '\t\t\tcompatible = "shared-dma-pool";',
          f"\t\t\treg = {reg(base, high)};",
          "\t\t\tno-map;",
          "\t\t};",
          "\t};",
          "#endif"]
s.append("};")
for name in conv:
    s += ["",
          f"/* PS GEM1 over EMIO into {name}; its management registers sit on GEM1's MDIO bus. */",
          "&gem1 {",
          "\tstatus = \"okay\";",
          "\tphy-mode = \"gmii\";",
          "\tgem1_mdio: mdio {",
          "\t\t#address-cells = <1>;",
          "\t\t#size-cells = <0>;",
          node(name, f"{name}@{int(cells[name][1]['C_PHYADDR']):x}",
               ['compatible = "xlnx,gmii-to-rgmii-1.0";', f"reg = <{int(cells[name][1]['C_PHYADDR'])}>;"]),
          "\t};",
          "};"]
out.mkdir(exist_ok=True)
(out / "pz_zu2cg_pl.dtsi").write_text("\n".join(s) + "\n")

# --- Board-level nodes ---------------------------------------------------------------
gpio_width = {n: int(cells[n][1]["C_GPIO_WIDTH"]) for n in cells if cells[n][0] == "axi_gpio"}
b = [hdr.format(what="PZ-ZU2CG Linux reference design: board-level devices on the PL peripherals"),
     "#include <dt-bindings/gpio/gpio.h>",
     "#include <dt-bindings/input/input.h>", "",
     "/ {",
     "\tleds {",
     '\t\tcompatible = "gpio-leds";']
for ctrl, names in LED_NAMES.items():
    for i, lbl in enumerate(names[:gpio_width[ctrl]]):
        b += ["", f"\t\t{lbl} {{",
              f'\t\t\tlabel = "{lbl}";',
              f"\t\t\tgpios = <&{ctrl} {i} GPIO_ACTIVE_HIGH>;"]
        if (ctrl, i) in LED_TRIGGER:
            b.append(f'\t\t\tlinux,default-trigger = "{LED_TRIGGER[(ctrl, i)]}";')
        b.append("\t\t};")
b += ["\t};", "",
      "\tgpio-keys {",
      '\t\tcompatible = "gpio-keys";',
      "\t\tautorepeat;"]
for i in range(gpio_width["gpio_key"]):
    b += ["", f"\t\tkey{i + 1} {{",
          f'\t\t\tlabel = "KEY{i + 1}";',
          f"\t\t\tlinux,code = <BTN_{i}>;",
          f"\t\t\tgpios = <&gpio_key {i} GPIO_ACTIVE_LOW>;",
          "\t\t\tdebounce-interval = <20>;",
          "\t\t};"]
b += ["\t};", "};", "",
      "&axi_iic_eeprom {",
      "\teeprom@50 {",
      '\t\tcompatible = "atmel,24c64";',
      "\t\treg = <0x50>;",
      "\t\tpagesize = <32>;",
      "\t};",
      "};", "",
      "/*",
      " * RTL8211F on the PL RGMII port (the Puzhi manual says KSZ9031, but the PHY ID registers",
      " * read 0x001c/0xc916). The gmii_to_rgmii core adds no clock skew (its MMCM outputs are",
      " * all at 0 degrees), so the PHY must add both RGMII delays. The Realtek driver sets them",
      " * only for rgmii* modes, so GEM1 is described as rgmii-id even though it talks GMII to the",
      " * core: on ZynqMP that only changes a USRIO write, which GEM0 (RGMII on MIO) also does.",
      " * Checked on hardware for GEM0 only (2026-11-14); the PL port is still untested.",
      " * The PHY is held in reset by EMIO GPIO 0 (PS GPIO line 78) until Linux releases it,",
      " * so its ID can't be probed: the compatible names it.",
      " */",
      "&gem1 {",
      '\tphy-mode = "rgmii-id";',
      "\tphy-handle = <&phy_pl>;",
      "};", "",
      "&gem1_mdio {",
      f"\tphy_pl: ethernet-phy@{PHY_ADDR} {{",
      '\t\tcompatible = "ethernet-phy-id001c.c916", "ethernet-phy-ieee802.3-c22";',
      f"\t\treg = <{PHY_ADDR}>;",
      f"\t\treset-gpios = <&gpio {PS_GPIO_EMIO0} GPIO_ACTIVE_LOW>;",
      "\t\treset-assert-us = <10000>;",
      "\t\treset-deassert-us = <1000>;"]
b += ["\t};", "};"]
for c in conv:
    b += ["", f"&{c} {{", "\tphy-handle = <&phy_pl>;", "};"]

for h, ctrl in HEADERS.items():
    p = cells[ctrl][1]
    n = int(p["C_GPIO_WIDTH"]) + (int(p["C_GPIO2_WIDTH"]) if p["C_IS_DUAL"] == "1" else 0)
    names = [line_names[h].get(i, "") for i in range(n)]
    rows = [", ".join(f'"{x}"' for x in names[i:i + 8]) for i in range(0, n, 8)]
    b += ["", f"/* {h.upper()} header: GPIO line = connector pin */",
          f"&{ctrl} {{",
          "\tgpio-line-names = " + ",\n\t\t".join(rows) + ";",
          "};"]
(out / "pz_zu2cg_board.dtsi").write_text("\n".join(b) + "\n")

print(f"wrote {out / 'pz_zu2cg_pl.dtsi'} and {out / 'pz_zu2cg_board.dtsi'}")
for name in sorted(addr, key=lambda n: addr[n][0]):
    print(f"  {name:16s} 0x{addr[name][0]:09x}  {'SPI %d' % irq[name] if name in irq else ''}")
